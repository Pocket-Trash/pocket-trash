import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import * as schema from "../packages/database/src/schema/index.ts";

/**
 * Serializes schema metadata for embedding in an inline script.
 *
 * @param {unknown} value - Schema metadata to serialize.
 * @returns {string} JavaScript-safe JSON.
 */
function serializeForScript(value) {
  return JSON.stringify(value, null, 6).replaceAll("<", "\\u003c");
}

/**
 * Replaces one required template marker.
 *
 * @param {string} content - Diagram template content.
 * @param {string} marker - Unique marker to replace.
 * @param {string} replacement - Generated JavaScript value.
 * @returns {string} Template content with the marker replaced.
 * @throws When the marker does not occur exactly once.
 */
function replaceExactlyOnce(content, marker, replacement) {
  const parts = content.split(marker);
  if (parts.length !== 2) {
    throw new Error(`Expected exactly one ${marker} marker.`);
  }
  return parts.join(replacement);
}

/**
 * Generates an interactive diagram from the checked-out Drizzle schema.
 *
 * @returns {Promise<void>} Promise resolved after the diagram is written.
 * @rejects When schema metadata or the HTML template is invalid.
 */
async function main() {
  const scriptDirectory = dirname(fileURLToPath(import.meta.url));
  const databaseRequire = createRequire(
    join(scriptDirectory, "..", "packages", "database", "package.json"),
  );
  const { is } = await import(databaseRequire.resolve("drizzle-orm"));
  const { getTableConfig, PgTable } = await import(
    databaseRequire.resolve("drizzle-orm/pg-core")
  );
  const templatePath = join(
    scriptDirectory,
    "database-schema-diagram.template.html",
  );
  const outputPath = join(
    scriptDirectory,
    "..",
    "docs",
    "database-schema-diagram.html",
  );
  const configurations = Object.values(schema)
    .filter((value) => is(value, PgTable))
    .map((table) => getTableConfig(table))
    .sort((left, right) => left.name.localeCompare(right.name));
  const tableIds = new Set();
  const tables = configurations.map((configuration) => {
    const id = configuration.schema
      ? `${configuration.schema}.${configuration.name}`
      : configuration.name;
    if (tableIds.has(id)) throw new Error(`Duplicate Drizzle table: ${id}`);
    tableIds.add(id);

    const primaryColumns = new Set([
      ...configuration.columns
        .filter((column) => column.primary)
        .map((column) => column.name),
      ...configuration.primaryKeys.flatMap((key) =>
        key.columns.map((column) => column.name),
      ),
    ]);
    const foreignColumns = new Set(
      configuration.foreignKeys.flatMap((key) =>
        key.reference().columns.map((column) => column.name),
      ),
    );

    return {
      areas: ["full"],
      fields: configuration.columns.map((column) => {
        const flags = [
          primaryColumns.has(column.name) ? "PK" : null,
          foreignColumns.has(column.name) ? "FK" : null,
          column.isUnique ? "UQ" : null,
        ].filter(Boolean);
        const suffix = column.notNull ? "" : "?";
        return `${column.name}${suffix} ${flags.join("/")} ${column.getSQLType()}`
          .replaceAll(/\s+/g, " ")
          .trim();
      }),
      id,
      name: id,
      status: "existing",
    };
  });
  const relationships = configurations.flatMap((configuration) => {
    const source = configuration.schema
      ? `${configuration.schema}.${configuration.name}`
      : configuration.name;
    return configuration.foreignKeys.map((key) => {
      const reference = key.reference();
      const targetConfiguration = getTableConfig(reference.foreignTable);
      const target = targetConfiguration.schema
        ? `${targetConfiguration.schema}.${targetConfiguration.name}`
        : targetConfiguration.name;
      if (!tableIds.has(target)) {
        throw new Error(`${source} references unexported table ${target}.`);
      }
      const columns = reference.columns.map((column) => column.name).join(", ");
      const foreignColumns = reference.foreignColumns
        .map((column) => column.name)
        .join(", ");
      return [source, target, `${columns} → ${foreignColumns}`];
    });
  });

  const template = await readFile(templatePath, "utf8");
  const withTables = replaceExactlyOnce(
    template,
    "__DATABASE_TABLES__",
    serializeForScript(tables),
  );
  const rendered = replaceExactlyOnce(
    withTables,
    "__DATABASE_RELATIONSHIPS__",
    serializeForScript(relationships),
  );
  const notice =
    "<!-- Generated by pnpm diagram:database. Edit scripts/database-schema-diagram.template.html or the Drizzle schema instead. -->\n";

  await writeFile(outputPath, notice + rendered);
  process.stdout.write(
    `Generated ${outputPath} (${tables.length} tables, ${relationships.length} relationships)\n`,
  );
}

await main();
