import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

/** Directory containing the pen schema generator and its editable template. */
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
/** Editable source for the generated pen schema diagram. */
const templatePath = join(scriptDirectory, "pen-schema-diagram.template.html");
/** Repository documentation artifact written by the generator. */
const outputPath = join(
  scriptDirectory,
  "..",
  "docs",
  "pen-schema-diagram.html",
);
/** Diagram template content. */
const template = await readFile(templatePath, "utf8");

/** Required template content that prevents generating an incomplete diagram. */
const requiredMarkers = [
  'id="pen-schema-erd"',
  'id="ps-graph"',
  "const tables = [",
  "const relationships = [",
];

for (const marker of requiredMarkers) {
  if (!template.includes(marker)) {
    throw new Error(`Template is missing required marker: ${marker}`);
  }
}

/** Warning prepended to the generated documentation artifact. */
const notice =
  "<!-- Generated by pnpm diagram:pen-schema. Edit scripts/pen-schema-diagram.template.html instead. -->\n";

await writeFile(outputPath, notice + template);
process.stdout.write(`Generated ${outputPath}\n`);
